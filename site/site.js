// --- search: the header trigger and ⌘K open a command palette over
// search-index.js (components, pages and their sections, generated by the
// build). Both load on first use: no page pays for them up front.
const palette = document.getElementById("site-palette");
let paletteReady = null;
function loadPalette() {
  paletteReady ??= Promise.all([
    import("../src/components/command-palette/command-palette.js"),
    import("./search-index.js"),
  ]).then(([, { default: entries }]) => {
    palette.actions = entries.map((e, i) => ({
      id: String(i),
      label: e.label,
      description: e.description,
      group: e.group,
      icon: e.icon,
      keywords: e.keywords,
      onSelect: () => {
        const url = new URL(e.href, SITE);
        if (url.pathname === location.pathname && url.hash) {
          // Same page: jump to the section (and keep it in the history).
          history.pushState(null, "", url.hash);
          settleOn(url.hash.slice(1));
        } else {
          location.href = url.href;
        }
      },
    }));
    return palette;
  });
  return paletteReady;
}
if (palette) {
  const mac = /Mac|iPhone|iPad/.test(navigator.platform || navigator.userAgent);
  for (const k of $$("[data-site-search-key]")) k.textContent = mac ? "⌘K" : "Ctrl K";
  for (const b of $$("[data-site-search]")) b.addEventListener("click", () => loadPalette().then((p) => p.show()));
  // ⌘K before the palette loads (once loaded, its own hotkey takes over).
  document.addEventListener("keydown", (e) => {
    if (customElements.get("ray-command-palette") || e.key.toLowerCase() !== "k" || !(mac ? e.metaKey : e.ctrlKey) || e.altKey || e.shiftKey) return;
    e.preventDefault();
    loadPalette().then((p) => p.show());
  });
}

// --- components page: the language of the examples' code (HTML / React /
// Vue). One choice for every example, remembered for the next visit. The
// code itself (docs/code/<component>.html) is fetched when "Code" opens.
const SOURCE_KEY = "ray-elements:code-language";
const switches = $$("[data-source-switch]");
let sourceLang = "html";
function showSource(lang) {
  sourceLang = lang;
  for (const sw of switches) {
    sw.value = lang;
    for (const pre of $$("[data-source]", sw.closest(".source"))) pre.hidden = pre.dataset.source !== lang;
  }
}
async function loadSource(details) {
  if (details.dataset.loaded) return;
  details.dataset.loaded = "loading";
  const body = details.querySelector(".source-body");
  try {
    const res = await fetch(new URL(details.dataset.codeSrc, SITE));
    if (!res.ok) throw new Error(String(res.status));
    body.innerHTML = await res.text();
    details.dataset.loaded = "yes";
    for (const pre of $$("[data-source]", body)) pre.hidden = pre.dataset.source !== sourceLang;
  } catch {
    delete details.dataset.loaded;
    body.querySelector(".source-status")?.replaceChildren("Could not load the code. ", Object.assign(document.createElement("a"), { href: new URL(details.dataset.codeSrc, SITE).href, textContent: "Open it" }), ".");
  }
}
for (const d of $$("details[data-code-src]")) {
  d.addEventListener("toggle", () => { if (d.open) loadSource(d); });
  if (d.open) loadSource(d);
}
if (switches.length) {
  let saved = null;
  try { saved = localStorage.getItem(SOURCE_KEY); } catch {}
  if (saved && saved !== "html") customElements.whenDefined("ray-segmented-control").then(() => showSource(saved));
  for (const sw of switches) {
    const pick = () => {
      showSource(sw.value);
      try { localStorage.setItem(SOURCE_KEY, sw.value); } catch {}
    };
    sw.addEventListener("change", pick);
    sw.addEventListener("input", pick);
  }
}

