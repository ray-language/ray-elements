<script setup lang="ts">
import { reactive, ref } from "vue";
import { notify } from "@raylang/elements";

// Every Ray* component is registered globally by app.use(RayElements) (typed via GlobalComponents).
const project = reactive({ name: "", template: "", license: "mit", git: true });
const reply = ref("");
const confirmOpen = ref(false);
const lastAction = ref("none");
const templates = [
  { value: "cli", label: "Command line" },
  { value: "web", label: "Web server (web)" },
  { value: "desktop", label: "Desktop app (std/ui)" },
];

async function submit() {
  const body = JSON.stringify(project);
  // Inside the std/ui window the raylang program answers; in a plain browser, echo.
  reply.value = window.ray ? await window.ray.request(body) : `no raylang backend; would send ${body}`;
  notify({ title: "Project created", message: reply.value, color: "green" });
}

function onMenu(e: CustomEvent<{ value: string }>) {
  lastAction.value = e.detail.value;
  if (e.detail.value === "reset") confirmOpen.value = true;
}

function onDialogClose(e: CustomEvent<{ returnValue: string }>) {
  if (e.detail.returnValue === "reset") Object.assign(project, { name: "", template: "", license: "mit", git: true });
}
</script>

<template>
  <main class="app">
    <header>
      <!-- A raw custom element works too (isCustomElement in vite.config.ts). -->
      <h1>New project <ray-badge color="gray" normal-case>Vue</ray-badge></h1>
      <RayThemeToggle />
    </header>

    <RayTabs model-value="create">
      <RayTab value="create">Create</RayTab>
      <RayTab value="about">About</RayTab>

      <RayTabPanel value="create">
        <RayCard with-border padding="lg">
          <form id="project" @submit.prevent="submit">
            <RayInput
              v-model="project.name"
              name="name"
              label="Name"
              placeholder="my-app"
              required
              pattern="[a-z][a-z0-9-]*"
              description="Lowercase letters, digits and dashes."
            />
            <RaySelect v-model="project.template" name="template" label="Template" placeholder="Pick a template" required :data="templates" />
            <RaySegmentedControl v-model="project.license" name="license" aria-label="License" :data="['mit', 'apache', 'none']" />
            <RaySwitch v-model="project.git" name="git" label="Initialize a git repository" />
            <div class="actions">
              <RayMenu placement="bottom-end" @ray-select="onMenu">
                <RayButton slot="trigger" variant="default">More</RayButton>
                <RayMenuItem value="duplicate">Duplicate</RayMenuItem>
                <RayMenuItem value="reset" color="red">Reset form…</RayMenuItem>
              </RayMenu>
              <RayButton type="submit">Create</RayButton>
            </div>
            <p id="reply" class="reply">{{ reply || `Last menu action: ${lastAction}` }}</p>
          </form>
        </RayCard>
      </RayTabPanel>

      <RayTabPanel value="about">
        <p>Vue wrappers (with v-model) generated by the ray-elements tools from each component.toml.</p>
      </RayTabPanel>
    </RayTabs>

    <RayDialog v-model="confirmOpen" label="Reset the form?" size="sm" @ray-close="onDialogClose">
      <p>Everything you typed will be lost.</p>
      <div slot="footer" style="display: contents">
        <RayButton variant="default" data-dialog-close="cancel">Cancel</RayButton>
        <RayButton color="red" data-dialog-close="reset">Reset</RayButton>
      </div>
    </RayDialog>
  </main>
</template>
