import { useState, type FormEvent } from "react";
import { notify } from "@raylang/elements";
import {
  RayBadge,
  RayButton,
  RayCard,
  RayDialog,
  RayInput,
  RayMenu,
  RayMenuItem,
  RaySegmentedControl,
  RaySelect,
  RaySwitch,
  RayTab,
  RayTabPanel,
  RayTabs,
  RayThemeToggle,
} from "@raylang/react";

type Project = { name: string; template: string; license: string; git: boolean };

export default function App() {
  const [project, setProject] = useState<Project>({ name: "", template: "", license: "mit", git: true });
  const [reply, setReply] = useState("");
  const [confirmOpen, setConfirmOpen] = useState(false);
  const [lastAction, setLastAction] = useState("none");

  const set = <K extends keyof Project>(key: K, value: Project[K]) => setProject((p) => ({ ...p, [key]: value }));

  async function submit(e: FormEvent) {
    e.preventDefault();
    const body = JSON.stringify(project);
    // Inside the std/ui window the raylang program answers; in a plain browser, echo.
    const answer = window.ray ? await window.ray.request(body) : `no raylang backend; would send ${body}`;
    setReply(answer);
    notify({ title: "Project created", message: answer, color: "green" });
  }

  return (
    <main className="app">
      <header>
        <h1>New project <RayBadge color="gray" normalCase>React</RayBadge></h1>
        <RayThemeToggle />
      </header>

      <RayTabs value="create">
        <RayTab value="create">Create</RayTab>
        <RayTab value="about">About</RayTab>

        <RayTabPanel value="create">
          <RayCard withBorder padding="lg">
            <form id="project" onSubmit={submit}>
              <RayInput
                name="name"
                label="Name"
                placeholder="my-app"
                required
                pattern="[a-z][a-z0-9-]*"
                description="Lowercase letters, digits and dashes."
                value={project.name}
                onInput={(e) => set("name", (e.currentTarget as HTMLInputElement).value)}
              />
              <RaySelect
                name="template"
                label="Template"
                placeholder="Pick a template"
                required
                data={[
                  { value: "cli", label: "Command line" },
                  { value: "web", label: "Web server (web)" },
                  { value: "desktop", label: "Desktop app (std/ui)" },
                ]}
                value={project.template}
                onChange={(e) => set("template", (e.currentTarget as HTMLSelectElement).value)}
              />
              <RaySegmentedControl
                name="license"
                aria-label="License"
                data={["mit", "apache", "none"]}
                value={project.license}
                onChange={(e) => set("license", (e.currentTarget as HTMLInputElement).value)}
              />
              <RaySwitch
                name="git"
                label="Initialize a git repository"
                checked={project.git}
                onChange={(e) => set("git", (e.currentTarget as HTMLInputElement).checked)}
              />
              <div className="actions">
                <RayMenu placement="bottom-end" onRaySelect={(e) => {
                  setLastAction(e.detail.value);
                  if (e.detail.value === "reset") setConfirmOpen(true);
                }}>
                  <RayButton slot="trigger" variant="default">More</RayButton>
                  <RayMenuItem value="duplicate">Duplicate</RayMenuItem>
                  <RayMenuItem value="reset" color="red">Reset form…</RayMenuItem>
                </RayMenu>
                <RayButton type="submit">Create</RayButton>
              </div>
              <p className="reply" id="reply">{reply || `Last menu action: ${lastAction}`}</p>
            </form>
          </RayCard>
        </RayTabPanel>

        <RayTabPanel value="about">
          <p>React wrappers generated by the ray-elements tools from each component.toml.</p>
        </RayTabPanel>
      </RayTabs>

      <RayDialog
        label="Reset the form?"
        size="sm"
        open={confirmOpen}
        onRayClose={(e) => {
          setConfirmOpen(false);
          if (e.detail.returnValue === "reset") setProject({ name: "", template: "", license: "mit", git: true });
        }}
      >
        <p>Everything you typed will be lost.</p>
        <div slot="footer" style={{ display: "contents" }}>
          <RayButton variant="default" data-dialog-close="cancel">Cancel</RayButton>
          <RayButton color="red" data-dialog-close="reset">Reset</RayButton>
        </div>
      </RayDialog>
    </main>
  );
}
